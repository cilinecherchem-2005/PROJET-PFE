const menuToggle = document.getElementById('menuToggle');
const sidebar = document.querySelector('.sidebar');
const themeToggle = document.getElementById('themeToggle');
const langSelect = document.getElementById('langSelect');

function appliquerTheme(theme) {
  const html = document.documentElement;
  if (theme === 'dark') {
    html.classList.add('theme-dark');
    themeToggle.textContent = traduction[langSelect.value].bouton_theme;
    localStorage.setItem('theme', 'dark');
  } else {
    html.classList.remove('theme-dark');
    themeToggle.textContent = traduction[langSelect.value].bouton_theme;
    localStorage.setItem('theme', 'light');
  }
}

function changerLangue(lang) {
  const textes = document.querySelectorAll('[data-i18n]');
  textes.forEach((element) => {
    const cle = element.getAttribute('data-i18n');
    if (traduction[lang] && traduction[lang][cle]) {
      element.textContent = traduction[lang][cle];
    }
  });
  localStorage.setItem('langue', lang);
}

if (menuToggle) {
  menuToggle.addEventListener('click', () => {
    sidebar.classList.toggle('show');
  });
}

if (themeToggle) {
  themeToggle.addEventListener('click', () => {
    const current = document.documentElement.classList.contains('theme-dark') ? 'dark' : 'light';
    appliquerTheme(current === 'dark' ? 'light' : 'dark');
  });
}

if (langSelect) {
  langSelect.addEventListener('change', (event) => {
    changerLangue(event.target.value);
  });
}

const themeStocke = localStorage.getItem('theme') || 'light';
const langueStockee = localStorage.getItem('langue') || 'fr';
langSelect.value = langueStockee;
appliquerTheme(themeStocke);
changerLangue(langueStockee);

// Graphiques - création simple si les éléments existent
const ctxOffres = document.getElementById('chartOffres');
const ctxCandidats = document.getElementById('chartCandidats');
if (ctxOffres) {
  const dataOffres = [window.totalOffres || 0, window.totalCVs || 0];
  new Chart(ctxOffres, {
    type: 'doughnut',
    data: {
      labels: ['Offres', 'CVs'],
      datasets: [{
        data: dataOffres,
        backgroundColor: ['#1f57ff', '#6c9cff']
      }]
    },
    options: { responsive: true, plugins: { legend: { position: 'bottom' } } }
  });
}
if (ctxCandidats) {
  const labels = window.candidatScores ? window.candidatScores.map((_, index) => `Candidat ${index + 1}`) : ['Candidat 1', 'Candidat 2', 'Candidat 3', 'Candidat 4', 'Candidat 5'];
  const dataScores = window.candidatScores && window.candidatScores.length ? window.candidatScores : [10, 20, 30, 40, 50];
  new Chart(ctxCandidats, {
    type: 'bar',
    data: {
      labels: labels,
      datasets: [{
        label: 'Score',
        data: dataScores,
        backgroundColor: '#1f57ff'
      }]
    },
    options: { responsive: true, scales: { y: { beginAtZero: true, max: 100 } } }
  });
}
